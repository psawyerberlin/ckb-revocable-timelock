// Bundles kit/recovery.ts into one IIFE and writes src/kit/assets.generated.ts with it and kit/template.html as
// string constants, so `generateKit` works in browsers and Node without file access.
// Usage: node scripts/build-kit.mjs [--check]   (--check exits 1 when the committed file is stale)
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const GENERATED = path.join(root, 'src', 'kit', 'assets.generated.ts');

/** Returns the source text of src/kit/assets.generated.ts. Deterministic for a given esbuild version (pinned). */
export async function buildKitAssets() {
  const r = await esbuild.build({
    absWorkingDir: root,
    entryPoints: ['kit/recovery.ts'],
    bundle: true, write: false, format: 'iife', platform: 'browser', target: 'es2020',
    minify: true, legalComments: 'eof', charset: 'utf8', sourcemap: false, logLevel: 'silent',
  });
  const js = r.outputFiles[0].text.replace(/<\/(script)/gi, '<\\/$1').trimEnd();
  const template = fs.readFileSync(path.join(root, 'kit', 'template.html'), 'utf8');
  const sha = crypto.createHash('sha256').update(template).update('\0').update(js).digest('hex');
  return [
    '// GENERATED by scripts/build-kit.mjs from kit/template.html and kit/recovery.ts (esbuild ' + esbuild.version + '). Do not edit.',
    `export const KIT_ASSETS_SHA256 = ${JSON.stringify(sha)};`,
    `export const KIT_TEMPLATE = ${JSON.stringify(template)};`,
    `export const KIT_RECOVERY_JS = ${JSON.stringify(js)};`,
    '',
  ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const src = await buildKitAssets();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(GENERATED) ? fs.readFileSync(GENERATED, 'utf8') : '';
    if (cur !== src) { console.error('src/kit/assets.generated.ts is stale: run npm run build:kit'); process.exit(1); }
  } else {
    fs.writeFileSync(GENERATED, src);
    console.log(`wrote ${path.relative(root, GENERATED)} (${src.length} bytes)`);
  }
}
